const DICTS: Record<Locale, Dict> = { fr, en, ar };

/** Arabic names shown as a secondary line in Latin locales. */
export const PRAYER_AR: Record<string, string> = {
  fajr: 'الفجر',
  dhuhr: 'الظهر',
  asr: 'العصر',
  maghrib: 'المغرب',
  isha: 'العشاء',
  sunrise: 'الشروق',
};

export function createTranslator(locale: Locale) {
  const dict = DICTS[locale] ?? DICTS.fr;
  return function t(key: MessageKey, vars?: Record<string, string | number>): string {
    let out = dict[key] ?? fr[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        out = out.split(`{${k}}`).join(String(v));
      }
    }
    return out;
  };
}

export type Translator = ReturnType<typeof createTranslator>;

export function dirFor(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

export function intlLocale(locale: Locale): string {
  return locale === 'ar' ? 'ar-MA' : locale === 'en' ? 'en-GB' : 'fr-FR';
}

export function detectLocale(): Locale {
  let stored: string | null = null;
  try {
    stored = typeof localStorage !== 'undefined' ? localStorage.getItem('azan.locale') : null;
  } catch {
    stored = null;
  }
  if (stored && (LOCALES as readonly string[]).includes(stored)) return stored as Locale;
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'fr';
  if (nav.startsWith('ar')) return 'ar';
  if (nav.startsWith('en')) return 'en';
  return 'fr';
}
