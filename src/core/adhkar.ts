/**
 * Returns the adhkar items belonging to a given category.
 */
export function getAdhkarByCategory(category: AdhkarCategory): AdhkarItem[] {
  return ADHKAR_LIST.filter((item) => item.category === category);
}

/**
 * Automatically suggests the relevant category based on current local hour:
 *  - Morning (04:00 to 12:00): 'morning'
 *  - Afternoon / Evening (12:00 to 03:59): 'evening'
 */
export function getCurrentAdhkarCategory(hour: number): AdhkarCategory {
  if (hour >= 4 && hour < 12) {
    return 'morning';
  }
  return 'evening';
}
